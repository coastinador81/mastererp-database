CREATE TABLE google_billing_sync (
    id uuid PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    google_subject text NOT NULL,
    project_id text NOT NULL,
    billing_account_name text NOT NULL,
    connected_at timestamptz NOT NULL,
    project_resource text,
    status text NOT NULL CHECK (status IN ('needs_setup','pending','ready','no_records','error')),
    service_state text NOT NULL DEFAULT 'unchecked',
    service_operation text,
    report_state text NOT NULL DEFAULT 'reserved',
    report_id text NOT NULL,
    report_operation text,
    report_started_at timestamptz,
    create_attempts integer NOT NULL DEFAULT 0,
    service_started_at timestamptz,
    period_start timestamptz NOT NULL,
    period_end timestamptz NOT NULL,
    prepared_at timestamptz,
    checked_at timestamptz,
    next_check_at timestamptz,
    consumption_eur numeric(24,2),
    currency text CHECK (currency IS NULL OR currency='EUR'),
    error_code text,
    attempts integer NOT NULL DEFAULT 0,
    lease_until timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(user_id,google_subject,project_id,billing_account_name,connected_at),
    CHECK (period_start<period_end),
    CHECK ((status='ready' AND consumption_eur IS NOT NULL AND currency='EUR') OR status<>'ready')
);
CREATE INDEX google_billing_sync_user ON google_billing_sync(user_id,updated_at DESC);
